"""React export: convert a single-file HTML page into a Vite + React project.

The conversion itself yields one ``.jsx`` component. With a configured (ready)
provider the component is produced by the LLM using ``_stream_llm`` and its
``code`` text deltas. Without one — mock mode — a fully deterministic,
always-valid component is built locally so tests and offline demos behave
predictably: the raw HTML is embedded verbatim via ``dangerouslySetInnerHTML``
behind an empty CSS constant.

``build_project_zip`` wraps that component in a ready-to-run Vite project
(``package.json``, ``index.html``, ``vite.config.js``, ``src/main.jsx``,
``src/App.jsx``, ``README.md``, ``.gitignore``) and returns the zip bytes.
Entries use a fixed timestamp so identical inputs produce identical archives.
"""

from __future__ import annotations

import io
import json
import re
import zipfile
from html import escape, unescape

from app.services.llm_service import (
    _stream_llm_with_fallback,
    _strip_code_fences,
    resolve_provider,
)
from app.services.token_usage import UsageAccumulator, usage_store

DEFAULT_TITLE = 'Purl React export'

# Fixed timestamp for every archive member keeps exports byte-for-byte stable.
_ZIP_DATE_TIME = (2026, 1, 1, 0, 0, 0)

_TITLE_RE = re.compile(r'<title[^>]*>(.*?)</title>', re.IGNORECASE | re.DOTALL)

_PACKAGE_JSON = """{
  "name": "purl-react-export",
  "private": true,
  "version": "0.0.0",
  "type": "module",
  "scripts": {
    "dev": "vite",
    "build": "vite build",
    "preview": "vite preview"
  },
  "dependencies": {
    "react": "^19.0.0",
    "react-dom": "^19.0.0"
  },
  "devDependencies": {
    "@vitejs/plugin-react": "^6.0.5",
    "vite": "^8.0.0"
  }
}
"""

_VITE_CONFIG = """import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';

export default defineConfig({
  plugins: [react()],
});
"""

_MAIN_JSX = """import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';

import App from './App.jsx';

createRoot(document.getElementById('root')).render(
  <StrictMode>
    <App />
  </StrictMode>,
);
"""

_GITIGNORE = """node_modules
dist
"""

_README = """# Purl React export

A ready-to-run [Vite](https://vite.dev/) + [React](https://react.dev/) project
generated by [Purl](https://github.com/lwakis/purl).

## Requirements

- Node.js 20 or newer
- npm

## Run it

```bash
npm install
npm run dev
```

Then open the URL Vite prints (usually <http://localhost:5173>).

## Build

```bash
npm run build
npm run preview
```

## Files

- `src/App.jsx` — the exported component
- `src/main.jsx` — React entry point
- `index.html` — HTML shell

> Generated by Purl. Review the code before shipping it to production.
"""


def extract_title(code: str) -> str:
    """Return the page title from *code*, HTML-escaped, or a default.

    Entities in the source title are decoded first so escaping happens exactly
    once (``Q &amp; A`` becomes ``Q &amp; A`` in ``index.html``, not
    ``Q &amp;amp; A``).
    """
    match = _TITLE_RE.search(code)
    if not match:
        return DEFAULT_TITLE
    title = match.group(1).strip()
    return escape(unescape(title)) if title else DEFAULT_TITLE


def build_project_zip(component_code: str, title: str = DEFAULT_TITLE) -> bytes:
    """Wrap *component_code* in a ready-to-run Vite + React project zip.

    *title* is interpolated into ``index.html`` as-is, so callers should pass
    an already escaped value (``extract_title`` does this). The archive carries
    no top-level folder and every entry has a fixed timestamp, making the
    output deterministic.
    """
    index_html = (
        '<!doctype html>\n'
        '<html lang="en">\n'
        '  <head>\n'
        '    <meta charset="UTF-8" />\n'
        '    <meta name="viewport" content="width=device-width, initial-scale=1.0" />\n'
        f'    <title>{title}</title>\n'
        '  </head>\n'
        '  <body>\n'
        '    <div id="root"></div>\n'
        '    <script type="module" src="/src/main.jsx"></script>\n'
        '  </body>\n'
        '</html>\n'
    )

    files = [
        ('package.json', _PACKAGE_JSON),
        ('index.html', index_html),
        ('vite.config.js', _VITE_CONFIG),
        ('src/main.jsx', _MAIN_JSX),
        ('src/App.jsx', component_code),
        ('README.md', _README),
        ('.gitignore', _GITIGNORE),
    ]

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, 'w', zipfile.ZIP_DEFLATED) as archive:
        for name, content in files:
            info = zipfile.ZipInfo(name, date_time=_ZIP_DATE_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, content)
    return buffer.getvalue()


class LLMProviderError(Exception):
    """Raised when the configured provider fails while exporting to React."""


_SYSTEM_PROMPT = (
    'You convert a single self-contained HTML page into ONE React functional '
    'component. Return ONLY the component code — no markdown code fences, no '
    'explanations, no import statements. Export a single default component '
    'named `App`. Use JSX conventions: `className` instead of `class`, '
    '`htmlFor` instead of `for`, and self-closed void elements. Keep the '
    'structure, text content and visual design identical to the source. Move '
    'all CSS from `<style>` tags into one template-literal constant named `css` '
    'and render it once via `<style>{css}</style>` inside the component. Convert '
    'any `<script>` logic into `useEffect` hooks or event handlers where '
    'reasonable. Do not use external libraries; inline SVG is fine. The result '
    'must compile as-is in a Vite or CRA project.'
)


def _mock_react(code: str) -> str:
    """Deterministic, always-valid component that embeds the HTML verbatim."""
    return (
        '// Mock React export: connect a provider for a real conversion.\n'
        '\n'
        'const css = ``;\n'
        '\n'
        f'const html = {json.dumps(code)};\n'
        '\n'
        'export default function App() {\n'
        '  return (\n'
        '    <div>\n'
        '      <style>{css}</style>\n'
        '      <div dangerouslySetInnerHTML={{ __html: html }} />\n'
        '    </div>\n'
        '  );\n'
        '}\n'
    )


async def convert_to_react(code: str, model: str | None = None) -> str:
    """Return *code* (a single HTML page) as one React functional component.

    Uses the configured LLM provider when ready; otherwise a deterministic
    mock component. Provider failures raise ``LLMProviderError`` for the router
    to map to HTTP 502.
    """
    provider = resolve_provider(model)

    if not provider.ready:
        return _mock_react(code)

    user_message = f'Convert this HTML page:\n\n```html\n{code}\n```'

    usage = UsageAccumulator()
    chunks: list[str] = []

    async for sse in _stream_llm_with_fallback(provider, _SYSTEM_PROMPT, user_message, usage=usage):
        if not sse.startswith('data: '):
            continue
        try:
            payload = json.loads(sse[6:])
        except (json.JSONDecodeError, IndexError):
            continue
        event_type = payload.get('type')
        if event_type == 'code':
            chunks.append(payload.get('content', ''))
        elif event_type == 'error':
            raise LLMProviderError(payload.get('content', 'llm_provider_error'))

    usage_store.add(None, usage.snapshot())

    converted = _strip_code_fences(''.join(chunks))
    if not converted:
        converted = _mock_react(code)
    return converted
